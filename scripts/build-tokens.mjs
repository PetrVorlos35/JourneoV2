// Generates src/styles/tokens.css from design/tokens.json (exported from the Journeo Figma library).
// Usage: npm run tokens          (write the file)
//        npm run tokens -- --check  (exit 1 if the file is out of date, for CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));
const outFile = resolve(root, 'src/styles/tokens.css');

const cssName = (name) => name.replace(/\//g, '-');
const px = (n) => `${n}px`;
const MOBILE_BREAKPOINT = '48rem'; // Tailwind md

// Primitives resolve to the Tailwind v4 palette the app already renders with, so a token
// is pixel-identical to the utility class it replaces (e.g. dark:bg-white/10).
const primitive = (name) => {
  const p = tokens.primitives[name];
  if (!p) throw new Error(`Unknown primitive "${name}" in design/tokens.json`);
  if (!p.tailwind) return p.hex;
  const base = `var(--color-${p.tailwind})`;
  return p.alpha != null ? `color-mix(in oklab, ${base} ${p.alpha}%, transparent)` : base;
};

// ---- runtime variables (names match the WEB code syntax shown in Figma Dev Mode)
const light = [];
const dark = [];
for (const [name, [l, d]] of Object.entries(tokens.color)) {
  light.push(`  --color-${cssName(name)}: ${primitive(l)};`);
  dark.push(`  --color-${cssName(name)}: ${primitive(d)};`);
}

// Typography and layout carry desktop/mobile modes: mobile first, desktop from md up.
const mobile = [];
const desktop = [];
for (const [name, [desk, mob]] of Object.entries(tokens.typography)) {
  if (!name.startsWith('size/')) continue;
  const v = `--type-${cssName(name)}`;
  mobile.push(`  ${v}: ${px(mob)};`);
  if (desk !== mob) desktop.push(`    ${v}: ${px(desk)};`);
}
for (const [name, [desk, mob]] of Object.entries(tokens.layout)) {
  if (name === 'modes') continue;
  const v = `--layout-${name}`;
  mobile.push(`  ${v}: ${px(mob)};`);
  if (desk !== mob) desktop.push(`    ${v}: ${px(desk)};`);
}

// ---- Tailwind theme: semantic utilities that follow the variables above
const theme = [];
const group = (prefix, ns, utilPrefix = '') => {
  for (const name of Object.keys(tokens.color).filter((n) => n.startsWith(prefix))) {
    const short = name.slice(prefix.length);
    theme.push(`  --${ns}-${utilPrefix}${short}: var(--color-${cssName(name)});`);
  }
};
theme.push('  /* bg-page, bg-field, bg-accent, … */');
group('bg/', 'background-color');
theme.push('  /* text-primary, text-muted, text-accent, … */');
group('text/', 'text-color');
theme.push('  /* text-icon-default, text-icon-muted, … (Lucide icons use currentColor) */');
group('icon/', 'text-color', 'icon-');
theme.push('  /* border-default, border-subtle, border-focus, … */');
group('border/', 'border-color');

theme.push('', '  /* rounded-control, rounded-soft, rounded-page, rounded-card */');
for (const [name, v] of Object.entries(tokens.radius)) {
  if (name === 'full') continue;
  theme.push(`  --radius-${name}: ${px(v)};`);
}

theme.push('', '  /* h-touch, w-sidebar, … */');
for (const [name, v] of Object.entries(tokens.size)) theme.push(`  --spacing-${name}: ${px(v)};`);

theme.push('', '  /* text-display, text-headline, … text-micro (size + line height + tracking + weight) */');
for (const [name, s] of Object.entries(tokens.textStyles)) {
  if (name.endsWith('Strong')) continue; // weight variants: combine the base style with font-semibold / font-bold
  let key = name.split('/')[1].toLowerCase();
  // text-<name> is shared with text colors; avoid swallowing e.g. text/plan (color) vs Body/Plan (type)
  if (tokens.color[`text/${key}`]) key = `${key}-size`;
  theme.push(`  --text-${key}: var(--type-size-${s.size});`);
  theme.push(`  --text-${key}--line-height: ${s.lineHeight};`);
  if (s.letterSpacing !== '0') theme.push(`  --text-${key}--letter-spacing: ${s.letterSpacing};`);
  theme.push(`  --text-${key}--font-weight: ${s.weight};`);
}

const SHADOW_NAMES = {
  'Elevation/Page lift': 'page',
  'Elevation/Card ambient': 'card',
  'Elevation/Tab merge': 'tab',
  'Elevation/Blue action glow': 'glow',
  'Elevation/Raised action glow': 'glow-raised',
  'Elevation/Popover': 'popover',
  'Elevation/Sheet lift': 'sheet',
  'Elevation/Overlay': 'overlay',
  'Focus/Ring': 'focus',
};
theme.push('', '  /* shadow-page, shadow-card, shadow-glow, shadow-focus, … */');
for (const [style, short] of Object.entries(SHADOW_NAMES)) {
  const layers = tokens.effects[style]
    .filter((e) => !e.type)
    .map((e) => `${px(e.x)} ${px(e.y)} ${px(e.blur)} ${px(e.spread)} var(--color-${cssName(e.token)})`);
  theme.push(`  --shadow-${short}: ${layers.join(', ')};`);
}

const css = `/*
 * AUTO-GENERATED by scripts/build-tokens.mjs from design/tokens.json. Do not edit.
 * Source of truth: ${tokens.meta.source} (v${tokens.meta.version}, exported ${tokens.meta.exportedAt})
 * Variable names match the WEB code syntax in Figma Dev Mode, e.g. var(--color-bg-page).
 */

:root {
${light.join('\n')}

${mobile.join('\n')}
}

@media (min-width: ${MOBILE_BREAKPOINT}) {
  :root {
${desktop.join('\n')}
  }
}

.dark {
${dark.join('\n')}
}

@theme inline {
${theme.join('\n')}
}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== css) {
    console.error('src/styles/tokens.css is out of date. Run `npm run tokens`.');
    process.exit(1);
  }
  console.log('tokens.css is up to date.');
} else {
  writeFileSync(outFile, css);
  console.log(`Wrote ${outFile} (${Object.keys(tokens.color).length} colors).`);
}
